def add(a: int, b: int) -> int:
    """
    计算两个整数之和。

    参数:
        a: 第一个整数。
        b: 第二个整数。

    返回:
        两个整数相加的结果。
    """
    return a + b


def subtract(a: int, b: int) -> int:
    """
    计算两个整数之差。

    参数:
        a: 第一个整数（被减数）。
        b: 第二个整数（减数）。

    返回:
        第一个整数减去第二个整数的结果。
    """
    return a - b
